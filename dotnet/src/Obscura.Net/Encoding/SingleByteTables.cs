namespace Obscura.Net;

/// <summary>
/// WHATWG single byte index tables for the pages .NET does not ship
/// (ISO-8859-10, ISO-8859-14, ISO-8859-16) plus x-user-defined. Each table maps
/// bytes 0x80..0xFF; bytes below 0x80 are always their ASCII code point, and
/// 0x80..0x9F are the C1 controls for the ISO-8859 parts.
/// </summary>
internal static class SingleByteTables
{
    internal static char[]? For(string name) => name switch
    {
        "ISO-8859-10" => Iso885910,
        "ISO-8859-14" => Iso885914,
        "ISO-8859-16" => Iso885916,
        "x-user-defined" => XUserDefined,
        _ => null,
    };

    /// <summary>Expand a 96 entry 0xA0..0xFF index into the full 0x80..0xFF table.</summary>
    private static char[] Build(ushort[] upperHalf)
    {
        ArgumentOutOfRangeException.ThrowIfNotEqual(upperHalf.Length, 96);
        var table = new char[128];
        for (var i = 0; i < 32; i++)
        {
            table[i] = (char)(0x80 + i);
        }

        for (var i = 0; i < 96; i++)
        {
            table[32 + i] = (char)upperHalf[i];
        }

        return table;
    }

