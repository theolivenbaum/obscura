    private static readonly char[] XUserDefined = BuildXUserDefined();

    private static char[] BuildXUserDefined()
    {
        var table = new char[128];
        for (var i = 0; i < 128; i++)
        {
            table[i] = (char)(0xF780 + i);
        }

